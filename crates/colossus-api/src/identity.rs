const MAX_AUTHORIZATION_ITEMS: usize = 512;

/// Exact public API scope names.
pub mod scopes {
    /// Create and execute agent runs.
    pub const RUNS_EXECUTE: &str = "runs:execute";
    /// Read runs and released run updates.
    pub const RUNS_READ: &str = "runs:read";
    /// Cancel runs owned by the caller.
    pub const RUNS_CONTROL: &str = "runs:control";
    /// Respond to ordinary user prompts.
    pub const PROMPTS_RESPOND: &str = "prompts:respond";
    /// Respond to effect approval requests.
    pub const APPROVALS_RESPOND: &str = "approvals:respond";
    /// Read caller-owned released artifact metadata and bytes.
    pub const ARTIFACTS_READ: &str = "artifacts:read";
    /// Reserve and upload caller-owned bounded artifacts.
    pub const ARTIFACTS_WRITE: &str = "artifacts:write";
}

/// Validated exact API scope.
#[derive(Clone, Eq, Ord, PartialEq, PartialOrd, Hash, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct ApiScope(String);

impl ApiScope {
    /// Validate one canonical scope.
    pub fn new(value: impl Into<String>) -> ApiResult<Self> {
        let value = value.into();
        token(&value, "scope", MAX_IDENTIFIER_BYTES)?;
        Ok(Self(value))
    }

    /// Return the canonical scope value.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl Debug for ApiScope {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> fmt::Result {
        formatter.debug_tuple("ApiScope").field(&self.0).finish()
    }
}

impl TryFrom<String> for ApiScope {
    type Error = ApiError;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        Self::new(value)
    }
}

impl From<ApiScope> for String {
    fn from(value: ApiScope) -> Self {
        value.0
    }
}

